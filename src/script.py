def extract_content(data):
    choices = data.get("choices")

    if not isinstance(choices, list):
        return ""

    if not choices:
        return ""

    first_choice = choices[0]

    if not isinstance(first_choice, dict):
        return ""

    message = first_choice.get("message")

    if not isinstance(message, dict):
        return ""

    content = message.get("content")

    if isinstance(content, str):
        return content.strip()

    if isinstance(content, list):
        text_parts = []

        for item in content:
            if not isinstance(item, dict):
                continue

            item_text = item.get("text")

            if isinstance(item_text, str):
                text_parts.append(
                    item_text
                )

        return "\n".join(
            text_parts
        ).strip()

    return ""


def request_openrouter(prompt, model):
    if not OPENROUTER_API_KEY:
        raise RuntimeError(
            "OPENROUTER_API_KEY is not configured"
        )

    url = (
        "https://openrouter.ai/api/v1/"
        "chat/completions"
    )

    headers = {
        "Authorization": (
            f"Bearer {OPENROUTER_API_KEY}"
        ),
        "Content-Type": "application/json",
        "HTTP-Referer": (
            "https://github.com/"
            "gowthammedia11/telugu-mystery-ai"
        ),
        "X-Title": "Telugu Mystery AI",
    }

    payload = {
        "model": model,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You write factual Telugu "
                    "documentary narration. "
                    "Follow all constraints exactly. "
                    "Return only the narration."
                ),
            },
            {
                "role": "user",
                "content": prompt,
            },
        ],
        "temperature": 0.45,
        "max_tokens": 4000,
    }

    response = requests.post(
        url,
        headers=headers,
        json=payload,
        timeout=180,
    )

    response_text = response.text.strip()

    if response.status_code >= 400:
        raise RuntimeError(
            f"HTTP {response.status_code}: "
            f"{response_text[:500]}"
        )

    try:
        data = response.json()
    except ValueError:
        raise RuntimeError(
            "OpenRouter returned invalid JSON: "
            f"{response_text[:500]}"
        )

    content = extract_content(data)

    if content:
        return content

    # Useful diagnostic information instead of silently
    # treating every empty response as the same failure.
    error_data = data.get("error")

    if error_data:
        if isinstance(error_data, dict):
            error_message = error_data.get(
                "message",
                "Unknown OpenRouter error",
            )

            raise RuntimeError(
                f"OpenRouter error: {error_message}"
            )

        raise RuntimeError(
            f"OpenRouter error: {error_data}"
        )

    choices = data.get("choices")

    if choices:
        first_choice = choices[0]

        finish_reason = ""

        if isinstance(
            first_choice,
            dict,
        ):
            finish_reason = first_choice.get(
                "finish_reason",
                "",
            )

            message = first_choice.get(
                "message",
                {},
            )

            if isinstance(message, dict):
                reasoning = message.get(
                    "reasoning",
                    "",
                )

                if reasoning:
                    raise RuntimeError(
                        "Model returned reasoning "
                        "but no final content"
                    )

        raise RuntimeError(
            "OpenRouter returned empty content "
            f"(finish_reason={finish_reason})"
        )

    raise RuntimeError(
        "OpenRouter returned empty content"
    )


def generate_script(topic_id, title, research):
    print("=" * 70)
    print("GENERATING LONG SCRIPT")
    print("=" * 70)

    prompt = build_prompt(
        topic_id,
        title,
        research,
    )

    last_error = "Unknown error"

    for attempt in range(
        1,
        MAX_ATTEMPTS + 1,
    ):
        model = MODELS[
            (attempt - 1) % len(MODELS)
        ]

        print(
            f"OPENROUTER SCRIPT ATTEMPT "
            f"{attempt}/{MAX_ATTEMPTS}"
        )

        print(
            f"MODEL: {model}"
        )

        try:
            raw_text = request_openrouter(
                prompt,
                model,
            )

            print(
                f"RAW SCRIPT LENGTH: "
                f"{len(raw_text)}"
            )

            if not raw_text:
                last_error = (
                    "EMPTY RESPONSE"
                )

                print(
                    "SCRIPT GENERATION ERROR: "
                    f"{last_error}"
                )

                time.sleep(2)
                continue

            cleaned = sanitize_final_script(
                raw_text
            )

            print(
                f"CLEANED SCRIPT LENGTH: "
                f"{len(cleaned)}"
            )

            if len(cleaned) > TARGET_MAX_CHARS:
                cleaned = trim_to_target(
                    cleaned,
                    TARGET_MAX_CHARS,
                )

                cleaned = sanitize_final_script(
                    cleaned
                )

                print(
                    f"TRIMMED SCRIPT LENGTH: "
                    f"{len(cleaned)}"
                )

            valid, reason = validate_script(
                cleaned
            )

            if valid:
                print(
                    "SCRIPT VALIDATION: PASSED"
                )

                print(
                    f"FINAL SCRIPT LENGTH: "
                    f"{len(cleaned)}"
                )

                return cleaned

            last_error = reason

            print(
                "SCRIPT VALIDATION FAILED: "
                f"{reason}"
            )

        except Exception as exc:
            last_error = str(exc)

            print(
                "SCRIPT GENERATION ERROR: "
                f"{last_error}"
            )

        time.sleep(2)

    raise RuntimeError(
        "Script generation failed after "
        f"{MAX_ATTEMPTS} attempts: "
        f"{last_error}"
    )


def save_script(topic_id, script_text):
    SCRIPTS_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    topic_id = str(
        topic_id
    ).zfill(3)

    path = (
        SCRIPTS_DIR
        / f"{topic_id}.txt"
    )

    with path.open(
        "w",
        encoding="utf-8",
    ) as file:
        file.write(
            script_text.strip()
        )

    print(
        f"SCRIPT SAVED: {path}"
    )

    return path


