import os
import re
import time
import requests

from pathlib import Path


BASE_DIR = Path(__file__).resolve().parent.parent

OPENROUTER_API_KEY = os.getenv("OPENROUTER_API_KEY", "").strip()

# Use stable free endpoints first, then the OpenRouter free router as a final fallback.
# These are current free model IDs available on OpenRouter.
MODELS = [
    "google/gemma-4-31b-it:free",
    "qwen/qwen3-30b-a3b:free",
    "nvidia/nemotron-3-super-120b-a12b:free",
    "openrouter/free",
]

MIN_CHARS = 4500
TARGET_MIN_CHARS = 5000
TARGET_MAX_CHARS = 5500
MAX_CHARS = 5700

MAX_ATTEMPTS = 6

SCRIPTS_DIR = BASE_DIR / "scripts"


def remove_urls(text):
    text = re.sub(
        r"https?://\S+",
        "",
        text,
        flags=re.IGNORECASE,
    )

    text = re.sub(
        r"www\.\S+",
        "",
        text,
        flags=re.IGNORECASE,
    )

    return text


def remove_coordinates(text):
    patterns = [
        r"\b\d{1,3}\s*°\s*\d{1,2}\s*[′']?\s*\d{0,2}(?:\.\d+)?\s*[″\"]?\s*[NS]\b",
        r"\b\d{1,3}\s*°\s*\d{1,2}\s*[′']?\s*\d{0,2}(?:\.\d+)?\s*[″\"]?\s*[EW]\b",
        r"\b\d{1,3}(?:\.\d+)?\s*[NS]\b",
        r"\b\d{1,3}(?:\.\d+)?\s*[EW]\b",
        r"\b(?:latitude|longitude)\s*[:\-]?\s*\d+(?:\.\d+)?\b",
        r"\b(?:lat|lon|lng)\s*[:\-]?\s*\d+(?:\.\d+)?\b",
        r"\b\d+(?:\.\d+)?\s*,\s*\d+(?:\.\d+)?\b",
    ]

    for pattern in patterns:
        text = re.sub(
            pattern,
            " ",
            text,
            flags=re.IGNORECASE,
        )

    return text


def remove_forbidden_measurements(text):
    def miles_to_km(match):
        value = float(match.group(1))
        km = value * 1.60934

        if km >= 100:
            return f"{round(km)} kilometres"

        return f"{round(km, 1)} kilometres"

    def feet_to_m(match):
        value = float(match.group(1))
        metres = value * 0.3048

        if metres >= 100:
            return f"{round(metres)} metres"

        return f"{round(metres, 1)} metres"

    def fahrenheit_to_celsius(match):
        value = float(match.group(1))
        celsius = (value - 32) * 5 / 9

        return f"{round(celsius, 1)} degrees Celsius"

    text = re.sub(
        r"(\d+(?:\.\d+)?)\s*(?:miles|mile|mi)\b",
        miles_to_km,
        text,
        flags=re.IGNORECASE,
    )

    text = re.sub(
        r"(\d+(?:\.\d+)?)\s*(?:feet|foot|ft)\b",
        feet_to_m,
        text,
        flags=re.IGNORECASE,
    )

    text = re.sub(
        r"(\d+(?:\.\d+)?)\s*(?:°F|degrees?\s+Fahrenheit)\b",
        fahrenheit_to_celsius,
        text,
        flags=re.IGNORECASE,
    )

    return text


def clean_text(text):
    text = remove_urls(text)
    text = remove_coordinates(text)
    text = remove_forbidden_measurements(text)

    text = re.sub(
        r"\b(?:latitude|longitude|coordinates?|gps coordinates?)\b",
        "",
        text,
        flags=re.IGNORECASE,
    )

    text = text.replace("\r", " ")
    text = text.replace("\n", " ")

    text = re.sub(
        r"\s+",
        " ",
        text,
    )

    return text.strip()


def split_sentences(text):
    text = text.strip()

    if not text:
        return []

    parts = re.split(
        r"(?<=[.!?।])\s+",
        text,
    )

    return [
        part.strip()
        for part in parts
        if part.strip()
    ]


def normalize_sentence(sentence):
    sentence = sentence.strip()

    sentence = re.sub(
        r"\s+",
        " ",
        sentence,
    )

    return sentence


def sentence_key(sentence):
    sentence = sentence.lower()

    sentence = re.sub(
        r"[^a-z0-9\u0C00-\u0C7F]+",
        " ",
        sentence,
    )

    sentence = re.sub(
        r"\s+",
        " ",
        sentence,
    )

    return sentence.strip()


def repetition_ratio(text):
    sentences = split_sentences(text)

    if len(sentences) < 5:
        return 0.0

    keys = [
        sentence_key(sentence)
        for sentence in sentences
    ]

    keys = [
        key
        for key in keys
        if len(key) > 15
    ]

    if not keys:
        return 0.0

    unique_count = len(set(keys))

    return 1 - (
        unique_count / len(keys)
    )


def contains_meta_text(text):
    lowered = text.lower()

    forbidden = [
        "as an ai",
        "as a language model",
        "ai generated",
        "generated by ai",
        "scriptwriter",
        "script writer",
        "here is the script",
        "here's the script",
        "in this script",
        "according to the prompt",
        "prompt",
        "instructions",
        "word count",
        "character count",
        "sources:",
        "references:",
        "youtube description",
        "thumbnail",
    ]

    return any(
        phrase in lowered
        for phrase in forbidden
    )


def contains_forbidden_content(text):
    lowered = text.lower()

    forbidden_patterns = [
        r"https?://",
        r"www\.",
        r"\b\d+(?:\.\d+)?\s*(?:miles?|mi)\b",
        r"\b\d+(?:\.\d+)?\s*(?:feet|foot|ft)\b",
        r"\blatitude\b",
        r"\blongitude\b",
        r"\bcoordinates?\b",
        r"\bgps coordinates?\b",
        r"\b\d{1,3}\s*°\s*\d{1,3}",
    ]

    for pattern in forbidden_patterns:
        if re.search(
            pattern,
            lowered,
            flags=re.IGNORECASE,
        ):
            return True

    return False


def sanitize_final_script(text):
    text = clean_text(text)

    sentences = split_sentences(text)

    cleaned_sentences = []
    seen = set()

    for sentence in sentences:
        sentence = normalize_sentence(sentence)

        if not sentence:
            continue

        key = sentence_key(sentence)

        if not key:
            continue

        if key in seen:
            continue

        seen.add(key)
        cleaned_sentences.append(sentence)

    text = " ".join(
        cleaned_sentences
    )

    text = clean_text(text)

    return text.strip()


def trim_to_target(text, max_chars=TARGET_MAX_CHARS):
    if len(text) <= max_chars:
        return text

    sentences = split_sentences(text)

    result = []
    current_length = 0

    for sentence in sentences:
        sentence = sentence.strip()

        if not sentence:
            continue

        extra_length = len(sentence)

        if result:
            extra_length += 1

        if (
            current_length + extra_length
            > max_chars
        ):
            break

        result.append(sentence)
        current_length += extra_length

    trimmed = " ".join(result).strip()

    if len(trimmed) >= MIN_CHARS:
        return trimmed

    fallback = text[:max_chars]

    fallback = fallback.rsplit(
        " ",
        1,
    )[0].strip()

    return fallback


def validate_script(text):
    if not text:
        return False, "EMPTY SCRIPT"

    length = len(text)

    if length < MIN_CHARS:
        return False, (
            f"TOO SHORT: {length} characters"
        )

    if length > MAX_CHARS:
        return False, (
            f"TOO LONG: {length} characters"
        )

    if contains_meta_text(text):
        return False, "META TEXT DETECTED"

    if contains_forbidden_content(text):
        return False, "FORBIDDEN CONTENT DETECTED"

    ratio = repetition_ratio(text)

    if ratio > 0.30:
        return False, (
            f"TOO REPETITIVE: {ratio:.2f}"
        )

    sentences = split_sentences(text)

    if len(sentences) < 25:
        return False, (
            f"TOO FEW SENTENCES: {len(sentences)}"
        )

    return True, "VALID"


